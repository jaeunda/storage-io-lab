#!/usr/bin/env python3
"""Draw the README figures as portable SVGs with outlined Noto Sans labels."""
import argparse
import json
from pathlib import Path
from xml.sax.saxutils import escape, quoteattr
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
INK, MUTED, LINE = "#172b46", "#53647b", "#cbd5e1"
PAPER, WHITE, TEAL, BLUE, AMBER = "#f5f7fb", "#ffffff", "#087f8c", "#345ad4", "#b05b24"
TINTS = {TEAL: "#e5f3f2", BLUE: "#eaf0fb", AMBER: "#fcf0e5"}


class Figure:
    def __init__(self, fonts, filename, height, title, subtitle, description):
        self.fonts, self.filename = fonts, filename
        self.width, self.height = 1120, height
        self.title, self.description = title, description
        self.items, self.glyphs = [], {}
        self.rect(0, 0, 1120, height, PAPER, radius=0)
        self.label(40, 40, "STORAGE / FILE PROCESSING", 12, TEAL, True)
        self.label(40, 84, title, 30, INK, True)
        self.label(40, 115, subtitle, 16, MUTED)
        self.path("M40 140 H1080", LINE)

    def rect(self, x, y, width, height, fill=WHITE, stroke=None, radius=12):
        self.items.append(f'<rect x="{x}" y="{y}" width="{width}" height="{height}" '
                          f'rx="{radius}" fill="{fill}"' +
                          (f' stroke="{stroke}"' if stroke else '') + '/>')

    def label(self, x, y, value, size=18, color=INK, bold=False, max_width=None):
        value = value.replace("→", "›")
        font_key = "b" if bold else "r"
        font = self.fonts[font_key]
        names = [font.getBestCmap()[ord(c)] for c in value]
        scale = size / font["head"].unitsPerEm
        width = sum(font["hmtx"][name][0] for name in names) * scale
        assert x >= 0 and x + width <= 1100 and 0 < y < self.height, (self.filename, value)
        assert max_width is None or width <= max_width, (self.filename, value, width, max_width)
        uses, advance = [], 0
        for name in names:
            ident = font_key + "-" + name.replace(".", "-")
            if ident not in self.glyphs:
                pen = SVGPathPen(font.getGlyphSet())
                font.getGlyphSet()[name].draw(pen)
                self.glyphs[ident] = f'<path id="{ident}" d="{pen.getCommands()}"/>'
            uses.append(f'<use href="#{ident}" x="{advance}"/>')
            advance += font["hmtx"][name][0]
        self.items.append(f'<g aria-label={quoteattr(value)} fill="{color}"><title>{escape(value)}</title>'
                          f'<g transform="translate({x:.3f} {y}) scale({scale:.7f} {-scale:.7f})">'
                          + ''.join(uses) + '</g></g>')

    def path(self, data, color=MUTED, arrow=False, dashed=False):
        self.items.append(f'<path d="{data}" fill="none" stroke="{color}" stroke-width="2" '
                          'stroke-linecap="round" stroke-linejoin="round"' +
                          (' marker-end="url(#arrow)"' if arrow else '') +
                          (' stroke-dasharray="5 5"' if dashed else '') + '/>')

    def panel(self, x, y, width, height, number, title, color):
        self.rect(x, y, width, height, WHITE, LINE)
        self.rect(x + 20, y + 20, 36, 30, TINTS[color], radius=6)
        self.label(x + 27, y + 41, number, 14, color, True)
        self.label(x + 20, y + 85, title, 22, INK, True, width - 40)

    def page(self, x, y, value, note, color=TEAL, width=225):
        self.rect(x, y, width, 80, TINTS[color], LINE, 8)
        self.label(x + 14, y + 31, value, 18, color, True, width - 28)
        self.label(x + 14, y + 60, note, 14, MUTED, max_width=width - 28)

    def save(self, out):
        marker = '<marker id="arrow" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="6" markerHeight="6" orient="auto"><path d="M0 1 L9 5 L0 9" fill="none" stroke="#53647b" stroke-width="1.5"/></marker>'
        svg = (f'<svg xmlns="http://www.w3.org/2000/svg" width="1120" height="{self.height}" '
               f'viewBox="0 0 1120 {self.height}" role="img" aria-labelledby="title desc">\n'
               f'<title id="title">{escape(self.title)}</title>\n'
               f'<desc id="desc">{escape(self.description)} Labels use outlined Noto Sans.</desc>\n'
               '<!-- Generated by tools/render_diagrams.py; accessible labels remain in aria-label and title. -->\n'
               f'<defs>{marker}{"".join(self.glyphs.values())}</defs>\n'
               + '\n'.join(self.items) + '\n</svg>\n')
        (out / self.filename).write_text(svg)


def draw(fonts, out, results):
    f = Figure(fonts, "storage-overview.svg", 565, "Three ways to manage stored state",
               "Independent C programs connect physical operations, logical identity, and reusable file slots.",
               "Flash I/O preserves neighboring pages during an update. Hybrid FTL appends versions and merges a full block. Record I/O links deleted slots and reuses them.")
    for x, num, title, lines, color in [
        (40, "01", "Flash device I/O", ["Page read / write", "Block erase", "Copy out, update, copy back"], BLUE),
        (395, "02", "Hybrid FTL", ["Logical block → physical block", "Append sector versions", "Scan backward; merge latest"], TEAL),
        (750, "03", "Record storage", ["8-byte header + 85-byte slots", "Sequential field search", "Delete chain → insert reuse"], AMBER),
    ]:
        f.panel(x, 178, 330, 235, num, title, color)
        for j, line in enumerate(lines):
            f.label(x + 20, 299 + j * 31, line, 16, MUTED, max_width=290)
    f.label(40, 458, "PRESERVE NEIGHBORS", 12, BLUE, True)
    f.label(395, 458, "PRESERVE LATEST VERSION", 12, TEAL, True)
    f.label(750, 458, "REUSE DELETED SPACE", 12, AMBER, True)
    f.path("M40 486 H1080", LINE)
    f.label(40, 524, "Each project owns its image or record file; these directories are independent executables.", 16, MUTED)
    f.save(out)

    f = Figure(fonts, "flash-update.svg", 650, "An update moves more than one page",
               "The physical page number stays fixed; neighboring live pages travel through a temporary block.",
               "An eight-page block contains one target and seven neighbors. Copy seven live neighbors out, erase the original block, write the updated target, copy seven neighbors back, and erase the temporary block. Measured driver calls: 37 reads, 15 writes, two erases.")
    f.label(40, 177, "SOURCE BLOCK / 8 PAGES", 13, BLUE, True)
    for i in range(8):
        f.page(40 + i * 131, 195, "P0" if i == 0 else f"P{i}", "target" if i == 0 else "live", AMBER if i == 0 else BLUE, 119)
    for x, num, title, detail, color in [
        (40, "1", "Copy neighbors", "7 pages → spare block", BLUE),
        (305, "2", "Erase + update", "1 erase + target write", AMBER),
        (570, "3", "Restore neighbors", "7 pages → original block", BLUE),
        (835, "4", "Release spare", "Erase temporary block", TEAL),
    ]:
        f.panel(x, 322, 245, 151, num, title, color)
        f.label(x + 20, 440, detail, 14, MUTED, max_width=205)
        if x < 835:
            f.path(f"M{x + 245} 399 H{x + 258}", arrow=True)
    f.rect(40, 511, 1040, 90, TINTS[TEAL])
    f.label(62, 545, "FULL-BLOCK UPDATE", 12, TEAL, True)
    f.label(62, 577, "37 driver reads   /   15 page writes   /   2 block erases", 22, INK, True)
    f.label(40, 631, "The CLI prints 14 reads here; its counter omits validation and empty-page probes.", 15, MUTED)
    f.save(out)

    f = Figure(fonts, "hybrid-mapping.svg", 675, "Keep identity; move the newest version",
               "One mapping entry per logical block; each physical page stores its LSN in the spare area.",
               "An example mapped block contains LSN 8 A1, LSN 9 E0, LSN 10 F0, and LSN 8 A2. A backward scan finds A2 first. To update LSN 8 again, merge the newest other sectors in reverse order, append A3, erase the old block, and switch its mapping.")
    f.rect(40, 172, 1040, 61, WHITE, LINE)
    f.label(60, 210, "LSN 8 / 4 → LBN 2", 20, TEAL, True)
    f.label(405, 210, "table[2] = { pbn: 0, last_offset: 3 }", 20, INK, True)
    f.label(40, 269, "PBN 0 / FULL", 13, BLUE, True)
    for x, text, note, color in [
        (40, "LSN 8 · A1", "superseded", AMBER), (305, "LSN 9 · E0", "latest for 9", BLUE),
        (570, "LSN 10 · F0", "latest for 10", BLUE), (835, "LSN 8 · A2", "latest for 8", TEAL),
    ]:
        f.page(x, 288, text, note, color, 245)
    f.path("M1055 390 H860", TEAL, arrow=True)
    f.label(550, 396, "READ 8: newest match first", 15, TEAL, True)
    f.label(40, 435, "WRITE 8 = A3: copy latest other sectors; discard both older versions of 8", 17, MUTED)
    f.label(40, 480, "FREE PBN 1 / AFTER MERGE", 13, TEAL, True)
    for x, text, note, color in [
        (40, "LSN 10 · F0", "copied first", BLUE), (305, "LSN 9 · E0", "copied second", BLUE),
        (570, "LSN 8 · A3", "new version", TEAL), (835, "0xff", "one empty page", AMBER),
    ]:
        f.page(x, 499, text, note, color, 245)
    f.path("M40 611 H1080", LINE)
    f.label(40, 648, "Erase PBN 0 → return it to the free list; table[2] becomes { pbn: 1, last_offset: 2 }.", 16, MUTED)
    f.save(out)

    f = Figure(fonts, "record-reuse.svg", 705, "A deleted record becomes an address",
               "Relative record numbers identify fixed slots; the file header anchors a persistent free chain.",
               "Four 85-byte slots follow an eight-byte header. Delete RRN 1, then RRN 3, and the header points to 3, which links to 1, then minus one. Insert overwrites RRN 3 and advances the head to 1, without growing the file.")
    f.label(40, 181, "BYTE ADDRESS = 8 + 85 × RRN", 16, INK, True)
    f.rect(40, 203, 1040, 59, WHITE, LINE)
    f.label(60, 240, "HEADER / 8 B", 18, TEAL, True)
    f.label(350, 240, "live_count: 2", 18, INK)
    f.label(685, 240, "free_head: 3", 18, AMBER, True)
    for x, text, note, color in [
        (40, "RRN 0 · live", "offset 8", BLUE), (305, "RRN 1 · deleted", "* | next = -1", AMBER),
        (570, "RRN 2 · live", "offset 178", BLUE), (835, "RRN 3 · deleted", "* | next = 1", AMBER),
    ]:
        f.page(x, 302, text, note, color, 245)
    f.path("M760 262 V281 H957 V294", AMBER, arrow=True)
    f.path("M955 382 V414 H427 V390", AMBER, arrow=True)
    f.label(546, 406, "free chain: 3 → 1 → -1", 15, AMBER, True)
    f.rect(40, 452, 1040, 93, TINTS[TEAL])
    f.label(62, 487, "INSERT: consume RRN 3", 21, TEAL, True)
    f.label(62, 522, "Read next = 1 → overwrite slot 3 → set live_count = 3, free_head = 1", 18, INK)
    f.label(40, 590, "MEASURED / 1,000 SLOTS", 12, TEAL, True)
    f.label(40, 634, "250 deleted + 250 reused", 28, INK, True)
    f.label(620, 634, "85,008 bytes → 85,008 bytes", 24, TEAL, True)
    f.label(40, 680, "750 surviving records stayed unchanged. Use insert after deletion; legacy append can overwrite a live slot.", 15, MUTED)
    f.save(out)

    f = Figure(fonts, "measured-results.svg", 595, "The workload determines copying cost",
               "Hybrid FTL: physical page writes / logical sector writes, with four pages per block.",
               "Measured write amplification is 1.000 for 1000 writes to one hot sector, 3.988 for 1004 writes while keeping a block's four sectors live, and 3.951 for 4096 deterministic mixed writes across 28 sectors. These count driver calls, not storage throughput.")
    f.label(40, 181, "WORKLOAD", 12, MUTED, True)
    f.label(400, 181, "WRITE AMPLIFICATION", 12, MUTED, True)
    f.label(912, 181, "LOGICAL WRITES", 12, MUTED, True)
    for i, (mode, title, detail, color) in enumerate([
        ("hot", "One hot sector", "Old versions fill the block", TEAL),
        ("full", "Four live sectors", "Every overwrite preserves 3 peers", BLUE),
        ("mixed", "Mixed / 28 sectors", "Fixed generator seed: 42", AMBER),
    ]):
        data, y = results["hybrid"][mode], 205 + i * 105
        f.label(40, y + 24, title, 20, INK, True)
        f.label(40, y + 51, detail, 14, MUTED)
        f.rect(400, y + 2, 420, 40, "#e4eaf2", radius=5)
        f.rect(400, y + 2, 420 * data["write_amplification"] / 4, 40, color, radius=5)
        f.label(832, y + 29, f'{data["write_amplification"]:.3f}×', 20, color, True)
        f.label(957, y + 29, f'{data["logical_writes"]:,}', 20, INK, True)
    f.path("M40 536 H1080", LINE)
    f.label(40, 575, "Driver calls measured with GNU ld --wrap; no NAND timing, fsync throughput, or cross-project speedup.", 15, MUTED)
    f.save(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("font_dir", type=Path, help="Directory containing NotoSans-Regular.ttf and NotoSans-Bold.ttf")
    parser.add_argument("--output", type=Path, default=ROOT / "docs/assets")
    args = parser.parse_args()
    fonts = {key: TTFont(args.font_dir / f"NotoSans-{name}.ttf")
             for key, name in [("r", "Regular"), ("b", "Bold")]}
    args.output.mkdir(parents=True, exist_ok=True)
    results = json.loads((ROOT / "experiments/results/latest.json").read_text())
    draw(fonts, args.output, results)
    print("Rendered five SVGs with outlined Noto Sans labels.")


if __name__ == "__main__":
    main()
